int main(void)
{
	uint8_t buf[1024];
	int failed = 0;
	size_t i;

	for (i = 0; i < sizeof(buf); i++)
		buf[i] = byte_at(i);

	for (i = 0; i < sizeof(vectors) / sizeof(vectors[0]); i++) {
		uint64_t got = hayahash64(buf, (ptrdiff_t)vectors[i].len,
		                          vectors[i].seed);
		if (got != vectors[i].want) {
			fprintf(stderr,
			        "FAIL len=%zu seed=%016llX got=%016llX "
			        "want=%016llX\n",
			        vectors[i].len,
			        (unsigned long long)vectors[i].seed,
			        (unsigned long long)got,
			        (unsigned long long)vectors[i].want);
			failed = 1;
		}
	}

	{
		uint8_t wide_buf[1000];
		uint32_t x = UINT32_C(0x9E3779B9);
		for (i = 0; i < sizeof(wide_buf); i++) {
			x ^= x << 13;
			x ^= x >> 17;
			x ^= x << 5;
			wide_buf[i] = (uint8_t)x;
		}
		for (i = 0; i < sizeof(vectors128) / sizeof(vectors128[0]); i++) {
			hayahash128_t got = hayahash128(
				wide_buf, (ptrdiff_t)vectors128[i].len, UINT64_C(0x1234));
			uint64_t narrow = hayahash64(
				wide_buf, (ptrdiff_t)vectors128[i].len, UINT64_C(0x1234));
			if (got.lo != narrow || got.hi != vectors128[i].hi) {
				fprintf(stderr,
				        "FAIL128 len=%zu got=%016llX:%016llX "
				        "want_hi=%016llX\n",
				        vectors128[i].len,
				        (unsigned long long)got.hi,
				        (unsigned long long)got.lo,
				        (unsigned long long)vectors128[i].hi);
				failed = 1;
			}
		}
	}

	/* SMHasher3 verification value over the direct interface. */
	{
		uint8_t key[256];
		uint8_t hashes[256 * 8];
		uint64_t total;
		memset(key, 0, sizeof(key));
		for (i = 0; i < 256; i++) {
			uint64_t h = hayahash64(key, (ptrdiff_t)i, 256 - i);
			hashes[i * 8 + 0] = (uint8_t)(h);
			hashes[i * 8 + 1] = (uint8_t)(h >> 8);
			hashes[i * 8 + 2] = (uint8_t)(h >> 16);
			hashes[i * 8 + 3] = (uint8_t)(h >> 24);
			hashes[i * 8 + 4] = (uint8_t)(h >> 32);
			hashes[i * 8 + 5] = (uint8_t)(h >> 40);
			hashes[i * 8 + 6] = (uint8_t)(h >> 48);
			hashes[i * 8 + 7] = (uint8_t)(h >> 56);
			key[i] = (uint8_t)i;
		}
		total = hayahash64(hashes, (ptrdiff_t)sizeof(hashes), 0);
		if ((uint32_t)total != 0x65F2AC15u) {
			fprintf(stderr,
			        "FAIL verification value: got=%08X want=65F2AC15\n",
			        (unsigned)(uint32_t)total);
			failed = 1;
		}
	}

	if (failed) {
		fprintf(stderr, "mips hayahash: %d failure(s)\n", failed);
		return 1;
	}
	puts("ok");
	return 0;
}
