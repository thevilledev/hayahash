func TestMatchesCReference(t *testing.T) {
	buf := make([]byte, 1024)
	for i := range buf {
		buf[i] = byteAt(i)
	}
	for _, v := range vectors {
		if got := hayahash.Hash64(buf[:v.len], v.seed); got != v.want {
			t.Errorf("len=%d seed=%#018X: got %#018X, want %#018X",
				v.len, v.seed, got, v.want)
		}
	}
}

// TestSMHasher3VerificationValue reproduces SMHasher3's self-test:
// hash the key prefix of length i with seed 256-i for i in 0..=255,
// concatenating the little-endian digests (key byte i is set to i
// after round i), then hash that buffer with seed 0. The low 32 bits
// must match the registered verification value.
func TestSMHasher3VerificationValue(t *testing.T) {
	var key [256]byte
	var hashes [256 * 8]byte
	for i := 0; i < 256; i++ {
		h := hayahash.Hash64(key[:i], uint64(256-i))
		binary.LittleEndian.PutUint64(hashes[i*8:], h)
		key[i] = byte(i)
	}
	total := hayahash.Hash64(hashes[:], 0)
	if got := uint32(total); got != 0x6B558D9D {
		t.Errorf("verification value: got %#010X, want 0x6B558D9D", got)
	}
}

func ExampleHash64() {
	fmt.Printf("%016X\n", hayahash.Hash64([]byte("hello world"), 0))
	// Output: F2172C5BD68EC576
}
