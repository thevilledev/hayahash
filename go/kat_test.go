// byteAt returns the deterministic key material shared with the C
// generator: byte(i) = (i*K + 0x2545F4914F6CDD1D) >> 56.
func byteAt(i int) byte {
	return byte((uint64(i)*0x9E3779B97F4A7C15 + 0x2545F4914F6CDD1D) >> 56)
}

