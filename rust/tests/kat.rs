/// Deterministic key material shared with the C generator:
/// `byte(i) = (i * K + 0x2545F4914F6CDD1D) >> 56`.
fn byte_at(i: usize) -> u8 {
    ((i as u64)
        .wrapping_mul(0x9E37_79B9_7F4A_7C15)
        .wrapping_add(0x2545_F491_4F6C_DD1D)
        >> 56) as u8
}

