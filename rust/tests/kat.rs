#[test]
fn matches_c_reference() {
    let mut buf = [0u8; 1024];
    for (i, b) in buf.iter_mut().enumerate() {
        *b = byte_at(i);
    }
    for &(len, seed, want) in VECTORS {
        assert_eq!(
            hayahash::hayahash64(&buf[..len], seed),
            want,
            "len={len} seed={seed:#018X}"
        );
    }
}

/// SMHasher3's self-test: hash the key prefix of length `i` with seed
/// `256 - i` for i in 0..=255, concatenating the little-endian digests
/// (key byte `i` is set to `i` after round `i`), then hash that buffer
/// with seed 0. The low 32 bits must match the registered verification
/// value.
#[test]
fn smhasher3_verification_value() {
    let mut key = [0u8; 256];
    let mut hashes = [0u8; 256 * 8];
    for i in 0..256 {
        let h = hayahash::hayahash64(&key[..i], (256 - i) as u64);
        hashes[i * 8..(i + 1) * 8].copy_from_slice(&h.to_le_bytes());
        key[i] = i as u8;
    }
    let total = hayahash::hayahash64(&hashes, 0);
    assert_eq!(total as u32, 0x99B3_876F);
}
